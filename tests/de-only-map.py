#!/usr/bin/env python3
"""Generate nginx/conf.d/redirects-de-only.conf (TEMPORARY, while only German is online).

Every English and Greek page URL (with and without the trailing slash) is mapped to the URL of its
German counterpart (name.en.md / name.el.md -> name.de.md). If there is no German page, or it is
switched off (build: render: never), the target is the German home page. default.conf answers a mapped URL
with a 302; everything else outside /de/ that is not a file gets the German 404 page.

Run after URLs change:  make de-only-map
Remove together with the German-only block in default.conf when EN/EL are switched on again.
"""
import pathlib
import re
import sys

CONTENT = pathlib.Path(__file__).resolve().parent.parent / "site" / "content"
HOME = {"en": "/", "de": "/de/", "el": "/el/"}


def front_matter(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    return m.group(1) if m else ""


def url_of(path, lang):
    fm = front_matter(path)
    m = re.search(r'^url:\s*"?([^"\n]+?)"?\s*$', fm, re.M)
    if m:
        return m.group(1)
    if path.name.startswith("_index.") and path.parent == CONTENT:
        return HOME[lang]
    return None


def hidden(path):
    return re.search(r"^\s*render:\s*never", front_matter(path), re.M) is not None


def main():
    pairs = {}
    for lang in ("en", "el"):
        for src in sorted(CONTENT.rglob(f"*.{lang}.md")):
            if hidden(src):
                continue
            url = url_of(src, lang)
            if not url or url == "/":  # "/" is handled by "location = /" in default.conf
                continue
            de = src.with_name(src.name[: -len(f".{lang}.md")] + ".de.md")
            # German counterpart, or the German home page when there is none (e.g. Greek job ads)
            target = url_of(de, "de") if de.exists() and not hidden(de) else HOME["de"]
            for key in {url, url.rstrip("/")} - {""}:
                pairs[key] = target or HOME["de"]
    out = [
        "# GENERATED by tests/de-only-map.py (make de-only-map) – do not edit by hand.",
        "# TEMPORARY while only German is online: English/Greek URL -> German page (302 in default.conf).",
        "map $uri $de_only_target {",
        '    default "";',
    ]
    width = max(len(k) for k in pairs) + 4
    out += [f'    "{k}"'.ljust(width + 6) + f" {v};" for k, v in sorted(pairs.items())]
    out.append("}")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
